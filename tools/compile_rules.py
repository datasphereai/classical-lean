#!/usr/bin/env python3
"""compile_rules: one registry of rules, and the rule text generated from it.

Why. The rule files only grow: HANDOFF.md section 6 went from 34 to 39 rules
between 2026-10-14 and 2026-10-18, and the record shows rules a session must
remember to apply catch little (Dustin's count of 2026-09-12: about 50 standing
rules, 6 enforced by a machine). Research the same week (IFScale, arXiv
2507.11538) measured instruction-following falling as the count of instructions
rises. A rule a tool enforces costs the reader nothing; a rule the reader must
remember costs attention every time. So the registry records, for each rule,
whether a tool enforces it, and the text a session reads is generated: rules a
tool enforces shrink to one line naming the tool, merged rules fold into the
rule that absorbed them, and the self-applied rules are held to a budget.

Registry: a TOML file (read with the standard library's tomllib, Python 3.11+).

    [meta]
    section = "HANDOFF.md section 6"
    budget_self_applied = 39     # Dustin's one in, one out: may fall, rises only on his yes
    budget_set_by = "Dustin 2026-10-18"

    [[rule]]
    n = 37                       # the rule's number; numbers are cited elsewhere, never reused
    title = "A name is probed before the text that uses it, and el.sh enforces it."
    body = '''Before it runs Lean, el.sh reads the text ...'''
    subject = "names"            # rules sharing a subject are candidates to merge
    status = "active"            # active | merged | retired
    merged_into = 0              # the surviving rule's n, when status = "merged"
    enforced_by = "el.sh"        # "" when no tool enforces it
    enforcement = "verified"     # proposed | verified: only a verified tool counts
    verified_by = "planted fault: an unprobed name; el.sh refused, logged NOT RUN"
    last_caught = "2026-10-16"   # optional: the last date the rule or its tool caught something

Commands (each exits 1 on a failure, 0 otherwise):
    compile_rules.py check  <registry> --base <registry at the base commit> | --first
                                                    validate the registry and the budget. Against
                                                    the base: no rule number may disappear, a
                                                    changed title or body needs a new change_note,
                                                    and the budget may not rise unless
                                                    meta.budget_raise_row is new (the push review
                                                    checks that row in the store: Dustin's ruling).
                                                    --first only for the commit that adds the registry.
    compile_rules.py render <registry>              print the generated block
    compile_rules.py drift  <registry> <file>       the block between the markers in <file>
                                                    must equal the generated one (no hand edits),
                                                    and nothing a reader could take for a rule may
                                                    sit outside it (v2, BREAK-IT-1 C2, C5)
    compile_rules.py splice <registry> <HANDOFF.md> <out.md>
                                                    put the render in place of section 6's numbered
                                                    list; refuses unless each anchor occurs once, in
                                                    order, inside section 6, and checks afterwards
                                                    that nothing outside the block changed (C1)
    compile_rules.py report <registry>              merge candidates, unverified tools,
                                                    rules with no recorded catch
Tests: python3 test_compile_rules.py
"""
import re
import sys

try:
    import tomllib
except ImportError:  # Python older than 3.11
    sys.stderr.write("compile_rules needs Python 3.11 or newer (tomllib)\n")
    sys.exit(2)

BEGIN = "<!-- rules:begin (generated by compile_rules.py from the rule registry; edit the registry, not this block) -->"
END = "<!-- rules:end -->"
STATUSES = {"active", "merged", "retired"}
RULE_KEYS = {"n", "title", "body", "subject", "status", "merged_into", "enforced_by", "enforcement",
             "verified_by", "last_caught", "change_note"}
META_KEYS = {"section", "budget_self_applied", "budget_set_by", "budget_raise_row", "allowed_bullets",
             "outside_sha256", "outside_change_note"}
# Fields whose change alters what a session must apply: a change needs a new change_note (BREAK-IT-1 C3).
GOVERNED = ("title", "body", "status", "merged_into", "enforced_by", "enforcement", "verified_by")
ROW_RE = re.compile(r"\b20\d{6}-\d{3}\b")
CONTROL_RE = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")
# What the readers of section 6 take for a rule (mkbrief.py: "^  N. ") and any other numbered shape.
READER_RULE_RE = re.compile(r"^  \d+\. ")
ANY_NUMBERED_RE = re.compile(r"^\s*\(?\d{1,3}[.)]\s")
SECTION6_RE = re.compile(r"^## 6\.")
RULES_START = "  1. *"
STANDING = "- **Standing answers**"
NUMBERED_RE = re.compile(r"^\s*\d{1,3}[.)]\s")
BULLET_RE = re.compile(r"^- ")
SUBSECTION_RE = re.compile(r"^## 6(?!\.\s)\S")
ENFORCEMENTS = {"proposed", "verified"}


def load(path):
    with open(path, "rb") as fh:
        return tomllib.load(fh)


def enforced(r):
    return bool(r.get("enforced_by")) and r.get("enforcement") == "verified"


def self_applied(rules):
    return [r for r in rules if r.get("status") == "active" and not enforced(r)]


def validate(reg):
    errs = []
    meta = reg.get("meta") or {}
    rules = reg.get("rule") or []
    budget = meta.get("budget_self_applied")
    for k in sorted(set(reg) - {"meta", "rule"}):
        errs.append("unknown table [%s] (a typo for [[rule]]?)" % k)
    for k in sorted(set(meta) - META_KEYS):
        errs.append("meta: unknown key %r" % k)
    if not rules:
        errs.append("the registry holds no [[rule]]")
    if isinstance(budget, bool) or not isinstance(budget, int) or budget < 0:
        errs.append("meta.budget_self_applied must be a whole number")
    if not meta.get("budget_set_by"):
        errs.append("meta.budget_set_by must say who set the budget and when")
    seen = {}
    for r in rules:
        if not isinstance(r, dict):
            errs.append("a [[rule]] entry is not a table")
            continue
        n = r.get("n")
        where = "rule %s" % n
        for k in sorted(set(r) - RULE_KEYS):
            errs.append("%s: unknown key %r" % (where, k))
        if isinstance(n, bool) or not isinstance(n, int) or n < 1:
            errs.append("%s: n must be a positive whole number" % where)
            continue
        if n in seen:
            errs.append("%s: the number is used twice" % where)
        seen[n] = r
        for f in ("title", "subject", "status"):
            if not isinstance(r.get(f), str) or not r.get(f).strip():
                errs.append("%s: %s is missing or empty" % (where, f))
        if not isinstance(r.get("body"), str):
            errs.append("%s: body must be text (it may be empty when the title is the whole rule)" % where)
        if r.get("status") not in STATUSES:
            errs.append("%s: status must be one of %s" % (where, sorted(STATUSES)))
        if r.get("enforced_by") and r.get("enforcement") not in ENFORCEMENTS:
            errs.append("%s: enforced_by is set, so enforcement must be proposed or verified" % where)
        if r.get("enforcement") == "verified" and not ROW_RE.search(str(r.get("verified_by") or "")):
            errs.append("%s: a verified tool needs verified_by naming the store row of the planted fault it "
                        "refused (YYYYMMDD-NNN)" % where)
        for f in ("title", "body"):
            v = r.get(f)
            if isinstance(v, str) and (CONTROL_RE.search(v) or (f == "title" and ("\n" in v or "\r" in v))):
                errs.append("%s: %s holds a line break or a control character" % (where, f))
        if "change_note" in r and (not isinstance(r.get("change_note"), str) or not r["change_note"].strip()):
            errs.append("%s: change_note must be text saying what changed and why" % where)
        if r.get("enforcement") == "verified" and not r.get("enforced_by"):
            errs.append("%s: enforcement is verified but enforced_by names no tool" % where)
    for r in rules:
        if not isinstance(r, dict):
            continue
        if r.get("status") == "merged":
            tgt = seen.get(r.get("merged_into"))
            if tgt is None:
                errs.append("rule %s: merged_into names no rule" % r.get("n"))
            elif tgt.get("status") != "active":
                errs.append("rule %s: merged into rule %s, which is not active"
                            % (r.get("n"), r.get("merged_into")))
    if isinstance(budget, int):
        count = len(self_applied(rules))
        if count > budget:
            errs.append("budget: %d self-applied rules, budget %d. Retire one, merge two, or give "
                        "one a tool that enforces it (one in, one out); only Dustin raises the "
                        "budget." % (count, budget))
    return errs


def fidelity(base, reg):
    """Against the base registry: no rule number disappears; a rule whose title, body, status,
    merge, tool or verification changed carries a new change_note (text that differs from the
    base's); retiring, merging or verifying a tool, or changing the tool of a rule that stays
    verified, needs that note to name a store row; a rule number that is not in the base needs a
    change_note naming a store row (v2.1, BREAK-IT-2 N9); and a change to the section-6 text outside
    the block needs a new outside_change_note naming a store row."""
    errs = []
    a = {r.get("n"): r for r in (base.get("rule") or []) if isinstance(r, dict)}
    b = {r.get("n"): r for r in (reg.get("rule") or []) if isinstance(r, dict)}
    for n in sorted(set(a) - set(b), key=str):
        errs.append("rule %s is in the base registry and missing now; rules are retired, never deleted" % n)
    for n in sorted(set(b) - set(a), key=str):
        if not ROW_RE.search(str(b[n].get("change_note") or "")):
            errs.append("rule %s is new: it needs a change_note naming the store row of Dustin's ruling that "
                        "adds it" % n)
    for n in sorted(set(a) & set(b), key=str):
        ra, rb = a[n], b[n]
        changed = [f for f in GOVERNED if ra.get(f) != rb.get(f)]
        if not changed:
            continue
        note = rb.get("change_note")
        if not isinstance(note, str) or not note.strip() or note == ra.get("change_note"):
            errs.append("rule %s: %s changed without a new change_note" % (n, ", ".join(changed)))
            continue
        needs_row = (("status" in changed and rb.get("status") in ("retired", "merged"))
                     or ("enforcement" in changed and rb.get("enforcement") == "verified")
                     or ("enforced_by" in changed and rb.get("enforcement") == "verified"))
        if needs_row and not ROW_RE.search(note):
            errs.append("rule %s: retiring, merging or verifying a tool, or changing a verified rule's tool, "
                        "needs a change_note naming the store row of Dustin's ruling or of the planted-fault "
                        "test" % n)
    ma, mb = base.get("meta") or {}, reg.get("meta") or {}
    if ma.get("outside_sha256") != mb.get("outside_sha256"):
        note = str(mb.get("outside_change_note") or "")
        if not ROW_RE.search(note) or note == str(ma.get("outside_change_note") or ""):
            errs.append("meta.outside_sha256 changed without a new outside_change_note naming a store row")
    return errs


def render(reg):
    meta = reg.get("meta") or {}
    rules = sorted(reg.get("rule") or [], key=lambda r: r["n"])
    sa = self_applied(rules)
    tool = [r for r in rules if r.get("status") == "active" and enforced(r)]
    merged = [r for r in rules if r.get("status") == "merged"]
    retired = [r for r in rules if r.get("status") == "retired"]
    absorbed = {}
    for r in merged:
        absorbed.setdefault(r["merged_into"], []).append(r["n"])
    # Layout kept compatible with the readers of section 6 (mkbrief.py quotes rule N from a line that
    # starts "  N. " up to the next such line or a line starting "- **"): each rule is one line at a
    # 2-space indent, and every part between rule lists starts with "- **" at column 0.
    out = [BEGIN, "  Rules to apply yourself (%d of a budget of %d, set by %s):"
           % (len(sa), meta.get("budget_self_applied", 0), meta.get("budget_set_by", "?"))]
    for r in sa:
        extra = ""
        if absorbed.get(r["n"]):
            extra = " (absorbs rule%s %s)" % ("s" if len(absorbed[r["n"]]) > 1 else "",
                                             ", ".join(str(x) for x in absorbed[r["n"]]))
        body = r["body"].replace("\r", "").replace("\n", " ")
        sep = "" if (not body or body[:1] in ",.;:") else " "
        out.append("  %d. *%s*%s%s%s" % (r["n"], r["title"].strip(), extra, sep, body))
    out.append("- **Rules a tool enforces** (%d; the tool refuses the act, so there is nothing to remember):"
               % len(tool))
    for r in tool:
        extra = ""
        if absorbed.get(r["n"]):
            extra = " (absorbs %s)" % ", ".join(str(x) for x in absorbed[r["n"]])
        out.append("  %d. *%s*%s Enforced by `%s`." % (r["n"], r["title"].strip(), extra, r["enforced_by"]))
    bits = []
    if merged:
        bits.append("merged: " + ", ".join("%d into %d" % (r["n"], r["merged_into"]) for r in merged))
    if retired:
        bits.append("retired: " + ", ".join(str(r["n"]) for r in retired))
    out.append("- **The full text** of every rule, the enforced, merged and retired ones included, is in the "
               "rule registry" + (" (" + "; ".join(bits) + ")" if bits else "") + ".")
    out.append(END)
    return "\n".join(out) + "\n"


def section6_bounds(lines):
    """(first line, end line) of the one '## 6.' section, or an error."""
    heads = [i for i, l in enumerate(lines) if SECTION6_RE.match(l)]
    if len(heads) != 1:
        return None, "the file must hold exactly one '## 6.' heading (found %d)" % len(heads)
    s = heads[0]
    e = next((i for i in range(s + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    return (s, e), None


def outside_sha(lines, s, e, a, b):
    """sha256 of section 6's lines outside the rule list or block (lines s..e minus a..b)."""
    import hashlib
    keep = lines[s:a] + ["<rules>"] + lines[b + 1:e]
    return hashlib.sha256("\n".join(l.rstrip() for l in keep).encode("utf-8")).hexdigest()


def extract(text, allowed_bullets=None, outside_want=None):
    """The generated block, or an error: exactly one BEGIN and one END, each alone on its line,
    in that order, inside the one '## 6.' section; no line a reader could take for a rule anywhere
    outside the block ('  N. ' in the whole file, any numbered line in section 6); no extra
    '## 6...' heading; when the registry lists allowed_bullets, no other top-level bullet in the
    section; and, when the registry records outside_sha256, section 6's text outside the block
    unchanged."""
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        return None, "the file must hold exactly one BEGIN and one END marker (found %d and %d)" % (
            text.count(BEGIN), text.count(END))
    a, b = text.find(BEGIN), text.find(END)
    if b < a:
        return None, "the END marker comes before the BEGIN marker"
    lines = text.split("\n")
    ia = next(i for i, l in enumerate(lines) if BEGIN in l)
    ib = next(i for i, l in enumerate(lines) if END in l)
    if lines[ia].rstrip() != BEGIN or lines[ib].rstrip() != END:
        return None, "a marker line holds other text"
    bounds, why = section6_bounds(lines)
    if why:
        return None, why
    s, e = bounds
    if not (s < ia < ib < e):
        return None, "the generated block is not inside section 6"
    reader = [l for i, l in enumerate(lines) if not ia <= i <= ib and READER_RULE_RE.match(l)]
    if reader:
        return None, "a line a reader would take for a rule, outside the generated block: %r" % reader[0][:80]
    stray6 = [l for i, l in enumerate(lines) if s < i < e and not ia <= i <= ib and ANY_NUMBERED_RE.match(l)]
    if stray6:
        return None, "a rule written by hand outside the generated block: %r" % stray6[0][:80]
    if outside_want is not None and outside_sha(lines, s, e, ia, ib) != outside_want:
        return None, ("section 6's text outside the generated block changed (sha256 %s, the registry records "
                      "%s); a change there goes through the registry's outside_sha256 with a store row"
                      % (outside_sha(lines, s, e, ia, ib)[:12], outside_want[:12]))
    sec_start = text.rfind("\n## ", 0, a)
    sec_start = 0 if sec_start == -1 else sec_start + 1
    sec_end = text.find("\n## ", b)
    sec_end = len(text) if sec_end == -1 else sec_end
    outside = (text[sec_start:a] + "\n" + text[b + len(END):sec_end]).splitlines()
    stray = [l for l in outside if NUMBERED_RE.match(l)]
    if stray:
        return None, "a rule written by hand outside the generated block: %r" % stray[0][:80]
    heads = [l for l in text.splitlines() if SUBSECTION_RE.match(l)]
    if heads:
        return None, "a section heading that extends section 6: %r" % heads[0][:80]
    if allowed_bullets is not None:
        for l in outside:
            if BULLET_RE.match(l):
                lead = l[2:].lstrip("*").strip()
                if not any(lead.startswith(x) for x in allowed_bullets):
                    return None, "a top-level bullet not in meta.allowed_bullets: %r" % l[:80]
    return text[a: b + len(END)] + "\n", None


def find_rule_list(lines):
    """(first line, last line) of section 6's numbered rule list in an unspliced HANDOFF, or an
    error: the section must be the only '## 6.', the first rule line and the Standing answers bullet
    must each occur exactly once in the whole file, both inside section 6, in that order."""
    bounds, why = section6_bounds(lines)
    if why:
        return None, why
    s, e = bounds
    starts = [i for i, l in enumerate(lines) if l.startswith(RULES_START)]
    stands = [i for i, l in enumerate(lines) if l.startswith(STANDING)]
    if len(starts) != 1 or len(stands) != 1:
        return None, ("the anchors must each occur once in the file: %d lines start %r, %d start %r"
                      % (len(starts), RULES_START, len(stands), STANDING))
    a, j = starts[0], stands[0]
    if not (s < a < j < e):
        return None, "the anchors are not inside section 6 in order (section %d-%d, list %d, standing %d)" % (
            s + 1, e, a + 1, j + 1)
    # the list ends at its last rule or indented continuation line: a paragraph at column 0 between the
    # list and the Standing answers is not part of it and is kept
    b, i = a, a + 1
    while i < j:
        if lines[i].strip() and not lines[i][:1].isspace():
            break
        if lines[i].strip():
            b = i
        i += 1
    return (a, b), None


def splice(reg, src, dst):
    with open(src, encoding="utf-8", newline="") as fh:
        raw = fh.read()
    if "\r" in raw:
        print("FAIL splice: %s has carriage returns" % src)
        return 1
    lines = raw.split("\n")
    span, why = find_rule_list(lines)
    if why:
        print("FAIL splice: " + why)
        return 1
    a, b = span
    s, e = section6_bounds(lines)[0]
    before = outside_sha(lines, s, e, a, b)
    want = (reg.get("meta") or {}).get("outside_sha256")
    if want and before != want:
        print("FAIL splice: section 6 outside the rule list is not what the registry recorded (%s vs %s)"
              % (before[:12], want[:12]))
        return 1
    block = render(reg).rstrip("\n").split("\n")
    out = lines[:a] + block + lines[b + 1:]
    if out[:a] != lines[:a] or out[a + len(block):] != lines[b + 1:]:
        print("FAIL splice: text outside the block changed")
        return 1
    s2, e2 = section6_bounds(out)[0]
    after = outside_sha(out, s2, e2, a, a + len(block) - 1)
    if after != before:
        print("FAIL splice: section 6 outside the block differs after splicing")
        return 1
    have, why = extract("\n".join(out), (reg.get("meta") or {}).get("allowed_bullets"), want or before)
    if have is None:
        print("FAIL splice: the result would not pass drift: " + why)
        return 1
    with open(dst, "x", encoding="utf-8", newline="") as fh:
        fh.write("\n".join(out))
    print("replaced lines %d to %d (%d lines) with %d lines; outside sha256 %s unchanged"
          % (a + 1, b + 1, b - a + 1, len(block), before[:12]))
    return 0


def report(reg):
    rules = reg.get("rule") or []
    sa = self_applied(rules)
    lines = []
    by = {}
    for r in sa:
        by.setdefault(r["subject"], []).append(r["n"])
    groups = sorted(((s, ns) for s, ns in by.items() if len(ns) > 1), key=lambda x: (-len(x[1]), x[0]))
    lines.append("Merge or mechanize candidates (a subject with more than one self-applied rule):")
    for s, ns in groups:
        lines.append("  %-16s rules %s" % (s, ", ".join(str(n) for n in sorted(ns))))
    if not groups:
        lines.append("  none")
    prop = [r for r in rules if r.get("status") == "active" and r.get("enforced_by")
            and r.get("enforcement") != "verified"]
    lines.append("Tools named but not yet verified by a planted fault (they count as self-applied):")
    for r in prop:
        lines.append("  rule %d: %s" % (r["n"], r["enforced_by"]))
    if not prop:
        lines.append("  none")
    never = [r["n"] for r in sa if not r.get("last_caught")]
    lines.append("Self-applied rules with no recorded catch (candidates to retire, Dustin's call): %s"
                 % (", ".join(str(n) for n in never) or "none"))
    lines.append("Totals: %d rules; %d self-applied (budget %s); %d enforced by a verified tool; "
                 "%d merged; %d retired." % (
                     len(rules), len(sa), (reg.get("meta") or {}).get("budget_self_applied"),
                     len([r for r in rules if r.get("status") == "active" and enforced(r)]),
                     len([r for r in rules if r.get("status") == "merged"]),
                     len([r for r in rules if r.get("status") == "retired"])))
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 3 or argv[1] not in ("check", "render", "drift", "report", "splice"):
        sys.stderr.write(__doc__)
        return 2
    reg = load(argv[2])
    errs = validate(reg)
    if argv[1] == "check" and "--base" not in argv and "--first" not in argv:
        sys.stderr.write("check needs --base <registry at the base commit> (or --first, only for the "
                         "commit that adds the registry)\n")
        return 2
    if argv[1] == "check" and "--base" in argv:
        i = argv.index("--base")
        if i + 1 >= len(argv):
            sys.stderr.write("--base needs the registry file from the base commit\n")
            return 2
        base_reg = load(argv[i + 1])
        errs.extend(fidelity(base_reg, reg))
        old = base_reg.get("meta") or {}
        new = reg.get("meta") or {}
        ob, nb = old.get("budget_self_applied"), new.get("budget_self_applied")
        if isinstance(ob, int) and isinstance(nb, int) and nb > ob:
            row = str(new.get("budget_raise_row") or "")
            if not re.fullmatch(r"20\d{6}-\d{3}", row) or row == str(old.get("budget_raise_row") or ""):
                errs.append("budget rose from %d to %d without a new budget_raise_row naming Dustin's "
                            "store row; only Dustin raises the budget" % (ob, nb))
    if argv[1] == "check":
        for e in errs:
            print("FAIL " + e)
        print("PASS" if not errs else "%d failure(s)" % len(errs))
        return 1 if errs else 0
    if errs:
        for e in errs:
            print("FAIL " + e)
        return 1
    if argv[1] == "render":
        sys.stdout.write(render(reg))
        return 0
    if argv[1] == "report":
        sys.stdout.write(report(reg))
        return 0
    if argv[1] == "splice":
        if len(argv) != 5:
            sys.stderr.write("splice needs <registry> <HANDOFF.md> <out.md>\n")
            return 2
        return splice(reg, argv[3], argv[4])
    if len(argv) < 4:
        sys.stderr.write("drift needs the file that holds the generated block\n")
        return 2
    meta = reg.get("meta") or {}
    if not meta.get("outside_sha256"):
        print("FAIL drift: the registry records no meta.outside_sha256, so text outside the block cannot "
              "be checked; rebuild the registry with build_registry.py v2")
        return 1
    with open(argv[3], encoding="utf-8", newline="") as fh:
        raw = fh.read()
    if "\r" in raw:
        print("FAIL drift: %s has carriage returns (CRLF line ends); readers split on \\n" % argv[3])
        return 1
    have, why = extract(raw, meta.get("allowed_bullets"), meta.get("outside_sha256"))
    want = render(reg)
    if have is None:
        print("FAIL drift: %s: %s" % (argv[3], why))
        return 1
    if have != want:
        print("FAIL drift: the block in %s differs from the registry's render; edit the registry "
              "and paste the render, never the block by hand" % argv[3])
        return 1
    print("PASS no drift")
    return 0


