def risk(loss, cell):
    """sum over observations x of P(x) * sum over actions y of K(x, y) * loss(y), in [0, inf],
    0 * inf = 0. loss values are Fractions or INF; cell = list of (P(x), K(x, .))."""
    total = F(0)
    for px, K in cell:
        for ky, ly in zip(K, loss):
            w = px * ky
            if w == 0:
                continue
            if ly is INF:
                return INF
            total += w * ly
    return total


def add_inf(a, b):
    return INF if a is INF or b is INF else a + b


def le_inf(a, b):
    if b is INF:
        return True
    if a is INF:
        return False
    return a <= b


