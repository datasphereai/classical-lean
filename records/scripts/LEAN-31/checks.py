def gamma_lib(q, th, v, k):
    return v * sum(th[j] * th[j + k] for j in range(q + 1 - k)) if k <= q else F(0)


def laurent_lhs(q, th, v):
    return {m: gamma_lib(q, th, v, abs(m)) for m in range(-q, q + 1)}


def laurent_rhs(q, th, v):
    c = {}
    for j in range(q + 1):
        for l in range(q + 1):
            c[j - l] = c.get(j - l, F(0)) + v * th[j] * th[l]
    return c


def walsh(r):
    """The 2^r - 1 nonconstant Walsh functions on 2^r points, as lists of +-1."""
    pts = list(range(2 ** r))
    fs = []
    for mask in range(1, 2 ** r):
        fs.append([F(-1) if bin(p & mask).count('1') % 2 else F(1) for p in pts])
    return fs


def cov(X, Y, mass):
    ex = sum(m * x for m, x in zip(mass, X))
    ey = sum(m * y for m, y in zip(mass, Y))
    return sum(m * (x - ex) * (y - ey) for m, x, y in zip(mass, X, Y))


