def complete_on_cells(cell_masses):
    """A function constant on the cells with mean 0 under every law must be 0: true when the
    matrix of cell masses (laws x cells) has rank = number of cells."""
    M = [list(r) for r in cell_masses]
    rows, cols = len(M), len(M[0])
    rank, r = 0, 0
    for c in range(cols):
        piv = next((i for i in range(r, rows) if M[i][c] != 0), None)
        if piv is None:
            continue
        M[r], M[piv] = M[piv], M[r]
        for i in range(rows):
            if i != r and M[i][c] != 0:
                f = M[i][c] / M[r][c]
                M[i] = [a - f * b for a, b in zip(M[i], M[r])]
        r += 1
        rank += 1
    return rank == cols


