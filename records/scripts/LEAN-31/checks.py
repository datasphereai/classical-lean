def holm_lean(q, x, i):
    m = len(x)
    for j in range(m):
        if x[j] <= x[i]:
            c = sum(1 for l in range(m) if x[j] <= x[l])
            if not x[j] <= (q / c if c else F(0)):
                return False
    return True


def holm_sorted(q, x):
    m = len(x)
    order = sorted(range(m), key=lambda i: x[i])
    rej = set()
    for r, i in enumerate(order, start=1):
        if x[i] <= q / (m - r + 1):
            rej.add(i)
        else:
            break
    return rej


def fwer(q, H, joint):
    """joint: list of (mass, p-value vector)."""
    return sum(w for w, x in joint if any(holm_lean(q, x, i) for i in H))


