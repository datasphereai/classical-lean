def real_lhs(q, gam, ang):
    cosk = ANGLES[ang][0]
    return sum(gam(abs(k)) * cosk(abs(k)) for k in range(-q, q + 1))


def real_rhs(q, th, v, ang):
    cosk, r2, sig = ANGLES[ang]
    c = sum(th[j] * cosk(j) for j in range(q + 1))
    s = sum(th[j] * sig(j) for j in range(q + 1))
    return v * (c * c + r2 * s * s)


